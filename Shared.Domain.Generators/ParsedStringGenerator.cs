using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Shared.Domain.Generators;

/// <summary>
/// Completes every valid <c>[ParsedString]</c> type with its private constructor, <c>Parse</c>,
/// public <c>TryParse</c>, <c>ToString</c>, <c>IParsedString</c> members and JSON converter.
/// Types breaking a rule in <see cref="ParsedStringRules"/> are skipped and reported by
/// <see cref="ParsedStringAnalyzer"/>.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class ParsedStringGenerator : IIncrementalGenerator
{
    private sealed record Model(string? Namespace, string Name, string Pattern, string Example);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var models = context.SyntaxProvider.ForAttributeWithMetadataName(
            ParsedStringRules.AttributeMetadataName,
            static (_, _) => true,
            static (attributeContext, _) =>
            {
                var type = (INamedTypeSymbol)attributeContext.TargetSymbol;
                var attribute = attributeContext.Attributes[0];
                var (pattern, example) = ParsedStringRules.PatternAndExample(attribute);

                return
                    ParsedStringRules.Violations(type, attribute).Any()
                    || pattern is null
                    || example is null
                    ? null
                    : new Model(
                        type.ContainingNamespace.IsGlobalNamespace
                            ? null
                            : type.ContainingNamespace.ToDisplayString(),
                        type.Name,
                        pattern,
                        example
                    );
            }
        );

        context.RegisterSourceOutput(models, static (sourceContext, model) =>
        {
            if (model is null)
                return;

            var name = model.Name;
            var pattern = SymbolDisplay.FormatLiteral(model.Pattern, quote: true);
            var example = SymbolDisplay.FormatLiteral(model.Example, quote: true);
            var error = SymbolDisplay.FormatLiteral(
                $"{name} should look like \"{model.Example}\"",
                quote: true
            );
            var namespaceLine = model.Namespace is null ? "" : $"namespace {model.Namespace};";

            sourceContext.AddSource(
                $"{model.Namespace}.{name}.g.cs".TrimStart('.'),
                $$"""
                // <auto-generated/>
                #nullable enable

                {{namespaceLine}}

                [global::System.Text.Json.Serialization.JsonConverter(typeof(global::Shared.Domain.ParsedStringJsonConverter<{{name}}>))]
                partial record {{name}} : global::Shared.Domain.IParsedString<{{name}}>
                {
                    public static string Pattern => {{pattern}};

                    public static string Example => {{example}};

                    private readonly string _value;

                    private {{name}}(string value)
                    {
                        _value = value;
                    }

                    /// <exception cref="global::System.FormatException"><paramref name="s"/> is not a valid <see cref="{{name}}"/>.</exception>
                    public static {{name}} Parse(string s, global::System.IFormatProvider? provider = null) =>
                        TryParse(s, provider, out var result)
                            ? result
                            : throw new global::System.FormatException({{error}});

                    public static bool TryParse(
                        [global::System.Diagnostics.CodeAnalysis.NotNullWhen(true)] string? s,
                        global::System.IFormatProvider? provider,
                        [global::System.Diagnostics.CodeAnalysis.NotNullWhen(true)] out {{name}}? result
                    )
                    {
                        result = s is null ? null : TryParse(s);
                        return result is not null;
                    }

                    public override string ToString() => _value;
                }

                """
            );
        });
    }
}
